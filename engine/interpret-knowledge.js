/** 按体系与维度取知识条目（同一条可挂多个维度，取交集） */
export function knowledgeFor(system, dimKey) {
  return KNOWLEDGE.filter((k) => k.system === system && k.dims.includes(dimKey));
}

/** 该体系所有「有异说／待核实」的条目：用于文末的诚实声明 */
export function caveatsFor(system) {
  return KNOWLEDGE.filter((k) => k.system === system && k.status !== 'settled');
}

