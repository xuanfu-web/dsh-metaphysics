/** 摇一支：不给 seed 走加密随机；给了 seed 用同一串数复现；except 是上一支，避开连抽同一支。 */
function drawNo(seed, except) {
  const rand = randomOf(seed);
  let no = 1 + Math.floor(rand() * GUANYIN_TOTAL);
  const prev = Number(except);
  if (Number.isInteger(prev) && prev >= 1 && prev <= GUANYIN_TOTAL && no === prev) {
    no = (no % GUANYIN_TOTAL) + 1;
  }
  return no;
}

/**
 * 观音灵签：一事一签，可重摇。
 * @param {{no?:number, seed?:number|string, except?:number, question?:string}} input
 *   no 指定 1–100；seed 用于复现同一支；except 传上一支的签号，避免重摇又摇回同一支；
 *   question 可留空——传统用法是心中默念，写下来只是便于回看。
 */
export function buildGuanyin(input = {}) {
  if (GUANYIN_LOTS.length !== GUANYIN_TOTAL) {
    throw fail('E_DATA', `观音灵签数据应为 ${GUANYIN_TOTAL} 支，实际 ${GUANYIN_LOTS.length} 支`);
  }
  const asked = input.no;
  if (!isSeed(input.seed)) {
    throw fail('E_INPUT', `观音灵签的 seed 要留空或给十进制数字（整数、小数、数字串都可），收到「${String(input.seed).slice(0, 24)}」`);
  }
  let no;
  if (asked !== undefined && asked !== null && asked !== '') {
    const n = Number(asked);
    if (!Number.isInteger(n) || n < 1 || n > GUANYIN_TOTAL) {
      throw fail('E_INPUT', `观音灵签的 no 要是 1–${GUANYIN_TOTAL} 的整数，收到「${String(asked).slice(0, 24)}」`);
    }
    no = n;
  } else {
    no = drawNo(input.seed, input.except);
  }
  const lot = GUANYIN_LOTS[no - 1];
  const copy = COPY[no];
  if (!lot || !copy) throw fail('E_DATA', `观音灵签第 ${no} 支缺少数据`);
  const question = typeof input.question === 'string'
    ? input.question.replace(/\s+/g, ' ').trim().slice(0, 80)
    : '';
  return {
    system: 'guanyin',
    meta: {
      no,
      total: GUANYIN_TOTAL,
      level: lot.level,
      palace: lot.palace,
      title: lot.title,
      question: question || null,
      method: asked !== undefined && asked !== null && asked !== '' ? '指定签号' : '摇签',
    },
    slip: {
      no,
      total: GUANYIN_TOTAL,
      level: lot.level,
      palace: lot.palace,
      title: lot.title,
      poem: lot.poem.slice(),
      omen: lot.omen || '',
      meaning: copy.meaning,
      advice: copy.advice,
      chips: copy.chips.slice(),
    },
    aside: GUANYIN_ASIDES[lot.level] || '',
    rules: GUANYIN_RULES,
    sources: GUANYIN_SOURCES.slice(),
    disclaimer: GUANYIN_SCOPE,
  };
}
