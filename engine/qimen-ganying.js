/** 天盘干 + 地盘干 → 十干克应条目；缺干或未收录返回 null */
export function ganyingOf(tian, di) {
  if (!tian || !di) return null;
  const hit = SHIGAN_YING[tian + di];
  if (!hit) return null;
  return { tian, di, key: tian + di, name: hit.name, text: hit.text, source: SHIGAN_YING_SOURCE };
}

